// Builds a Confluence "safety signal brief" (storage format) for a safety committee.
// Pure and unit-tested; every statement comes from stored, redacted records.
import { CATEGORIES, DEFENCES } from './lexicon.js';
import { sliceProfile } from './signals.js';
import { recommend } from './rca.js';

const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const catLabel = (id) => CATEGORIES.find((c) => c.id === id)?.label || 'Other';
const defLabel = (id) => DEFENCES.find((d) => d.id === id)?.label || id;
const STRENGTH_COLOUR = { strong: 'Green', intermediate: 'Blue', weak: 'Grey' };

const status = (title, colour) =>
  `<ac:structured-macro ac:name="status"><ac:parameter ac:name="title">${esc(title)}</ac:parameter><ac:parameter ac:name="colour">${colour}</ac:parameter></ac:structured-macro>`;
const panel = (type, body) => `<ac:structured-macro ac:name="${type}"><ac:rich-text-body>${body}</ac:rich-text-body></ac:structured-macro>`;
const jiraLink = (baseUrl, key) => (baseUrl ? `<a href="${esc(baseUrl)}/browse/${esc(key)}">${esc(key)}</a>` : esc(key));

export function briefTitle(signal, asOf) {
  return `Safety signal brief: ${signal.title} (${asOf})`;
}

/**
 * @param {object} signal     from detectSignals()
 * @param {Array}  records    the member records of the signal
 * @param {object} opts       { asOf, protocols (assessed), baseUrl (Jira site URL) }
 */
export function buildSignalBrief(signal, records, opts = {}) {
  const { asOf = new Date().toISOString().slice(0, 10), protocols = [], baseUrl = '' } = opts;
  const members = records.filter((r) => signal.keys.includes(r.key)).sort((a, b) => a.eventDate.localeCompare(b.eventDate));
  const profile = sliceProfile(members);
  const recs = recommend(profile).slice(0, 6);
  const defences = {};
  for (const r of members) for (const d of r.defences || []) defences[d] = (defences[d] || 0) + 1;
  const reached = members.filter((r) => r.outcome !== 'near-miss').length;
  const stale = protocols.filter((p) => p.stale);

  const parts = [];
  parts.push(
    panel(
      'info',
      `<p><strong>${esc(signal.title)}.</strong> ${members.length} reports from ${esc(signal.firstSeen)} to ${esc(signal.lastSeen)}; ` +
        `${reached ? `${reached} reached the patient.` : 'all were caught before reaching the patient.'} ` +
        `Generated by Slice on ${esc(asOf)} from redacted reports. Blame-free; for safety learning, not clinical advice.</p>`
    )
  );

  parts.push('<h2>Where the holes lined up</h2>');
  parts.push('<table><tbody><tr><th>Layer</th><th>Reports with a hole</th><th>Contributing factors</th></tr>');
  for (const l of profile) {
    parts.push(
      `<tr><td>${status(l.short, l.holes ? 'Red' : 'Green')}</td><td>${l.holes} / ${l.of}</td><td>${
        l.factors.length ? l.factors.map((f) => `${esc(f.label)} (${f.count})`).join(', ') : 'No hole found'
      }</td></tr>`
    );
  }
  parts.push('</tbody></table>');

  parts.push('<h2>The slices that held</h2>');
  const held = Object.entries(defences).sort((a, b) => b[1] - a[1]);
  parts.push(
    held.length
      ? `<ul>${held.map(([d, n]) => `<li>${esc(defLabel(d))}: caught the error in ${n} report${n > 1 ? 's' : ''}</li>`).join('')}</ul><p>Protect these defences: they are the reason these stayed near-misses.</p>`
      : '<p>No defence was recorded. Ask reporters what caught the error.</p>'
  );

  parts.push('<h2>Recommended system fixes</h2>');
  parts.push('<p>Ranked by the action hierarchy: strong (forcing functions, redesign) before intermediate (standardisation, checks) before weak (training, policy).</p>');
  parts.push('<table><tbody><tr><th>Strength</th><th>Action</th><th>Addresses</th></tr>');
  for (const r of recs) {
    parts.push(`<tr><td>${status(r.strength, STRENGTH_COLOUR[r.strength] || 'Grey')}</td><td>${esc(r.text)}</td><td>${esc(r.addresses)}</td></tr>`);
  }
  parts.push('</tbody></table>');

  if (protocols.length) {
    parts.push('<h2>Related protocols</h2><ul>');
    for (const p of protocols) {
      const link = p.url ? `<a href="${esc(p.url)}">${esc(p.title)}</a>` : esc(p.title);
      parts.push(`<li>${link}: ${p.stale ? `${status(`stale · ${p.ageMonths} months`, 'Yellow')}` : status('current', 'Green')}</li>`);
    }
    parts.push('</ul>');
    if (stale.length) parts.push(panel('warning', `<p>${stale.length} related protocol${stale.length > 1 ? 's are' : ' is'} overdue for review (more than 24 months).</p>`));
  }

  parts.push('<h2>Timeline of reports</h2>');
  parts.push('<table><tbody><tr><th>Date</th><th>Report</th><th>Summary (redacted)</th><th>Category</th><th>Outcome</th></tr>');
  for (const r of members) {
    parts.push(
      `<tr><td>${esc(r.eventDate)}</td><td>${jiraLink(baseUrl, r.key)}</td><td>${esc(r.summary)}</td><td>${esc(catLabel(r.category))}</td><td>${status(
        r.outcome,
        r.outcome === 'near-miss' ? 'Green' : 'Red'
      )}</td></tr>`
    );
  }
  parts.push('</tbody></table>');

  parts.push('<h2>Decisions for the safety committee</h2>');
  parts.push('<ac:task-list>');
  parts.push('<ac:task><ac:task-status>incomplete</ac:task-status><ac:task-body>Agree which recommended fixes to adopt, and an owner for each</ac:task-body></ac:task>');
  if (stale.length) parts.push('<ac:task><ac:task-status>incomplete</ac:task-status><ac:task-body>Schedule review of the overdue protocol(s)</ac:task-body></ac:task>');
  parts.push('<ac:task><ac:task-status>incomplete</ac:task-status><ac:task-body>Share learning with the teams involved, without attributing blame</ac:task-body></ac:task>');
  parts.push('</ac:task-list>');

  return { title: briefTitle(signal, asOf), body: parts.join('\n'), reports: members.length, fixes: recs.length };
}
